#!/usr/bin/env python3
"""Generate docs/evidence.md - the table a buyer reads before believing anything.

Nothing here is hand-typed: every row is re-derived from the committed result files and the commit they
came from. A row that cannot be reproduced is removed rather than explained.
"""
import glob
import hashlib
import io
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import equality  # the same digest the gate uses, so the table cannot disagree with the gate



VERSION_VALUE = (io.open(os.path.join(REPO, "VERSION"), encoding="utf-8").read().strip()
               if os.path.isfile(os.path.join(REPO, "VERSION")) else "ABSENT")
def run(*a):
    r = subprocess.run(list(a), cwd=REPO, capture_output=True, text=True,
                       encoding="utf-8", errors="replace", shell=False)
    return r.returncode, r.stdout.strip(), r.stderr.strip()


def load_port(port_dir):
    cells = {}
    bad = 0
    for f in sorted(glob.glob(os.path.join(port_dir, "**", "*.json"), recursive=True)):
        try:
            c = json.loads(io.open(f, encoding="utf-8").read())
        except ValueError:
            bad += 1
            continue
        if not isinstance(c, dict) or not c.get("case_id"):
            bad += 1
            continue
        key = equality.key_of(c)
        cells[key] = c
    return cells, bad


def main():
    _, head, _ = run("git", "rev-parse", "--short", "HEAD")
    _, head_full, _ = run("git", "rev-parse", "HEAD")
    dirty_rc, dirty, _ = run("git", "status", "--porcelain", "-uall")
    # hash the raw bytes: decoding a face with a guessed codec and then hashing it produced a
    # digest that disagreed with the lock table, which is exactly the failure this project keeps
    # finding in itself. No text mode on this path.
    rb = subprocess.run(["git", "cat-file", "blob", "HEAD:spec/cases.yaml"], cwd=REPO,
                        capture_output=True, shell=False)
    spec_digest = hashlib.sha256(rb.stdout).hexdigest() if rb.returncode == 0 else "unreadable"
    if rb.returncode != 0:
        print("WARN spec blob unreadable rc=%d" % rb.returncode)

    # the same face rule the gate uses: results/<port>.<os>.<arch>/ only. Measured reason: this table used
    # to print 9 rows for 6 ports, because results/ also carried earlier revisions of the same ports under
    # other names, and a reader counted nine ports.
    ports, files_seen, problems, xcheck, skipped = equality.discover()
    extras = ports.pop("_extra_counts", {})
    man = json.load(io.open(equality.REQUIRED, encoding="utf-8"))
    req = set((r["case_group"], r["case_id"], tuple(sorted((r.get("sub_identity") or {}).items())))
              for r in man["required_cells"])
    ports_list = []
    for port in sorted(ports):
        cells = {k: lst[0] for k, lst in ports[port].items() if k[0] != "tapi"}
        matched = len(set(cells) & req)
        if not cells:
            ports_list.append((port, "%s.windows.x64" % port, None, 0, "no canonical face found"))
            continue
        joined = "\n".join("%s %s" % (equality.fmt(k), equality.digest(c)[0])
                           for k, c in sorted(cells.items()))
        digest = hashlib.sha256(joined.encode("utf-8")).hexdigest()
        env = next(iter(cells.values()))
        ports_list.append((port, "%s.windows.x64" % port, digest[:16], matched,
                           "%s / %s / %s  (records=%d, extra-flagged=%d, tapi held out)"
                           % (env.get("os", "?"), env.get("arch", "?"), env.get("os_version", "?")[:24],
                              files_seen.get(port, 0), extras.get(port, 0))))

    rows = []

    rc_eq, out_eq, _ = run(sys.executable, os.path.join(HERE, "equality.py"))
    verdict = "NOT-COMPARABLE (rc=%d)" % rc_eq
    for line in out_eq.splitlines():
        if line.startswith("OUTCOME="):
            verdict = line.strip()
    rc_st, out_st, _ = run(sys.executable, os.path.join(HERE, "selftest.py"),
                           "--scratch-root", os.path.join(os.environ.get("TEMP", "/tmp"), "sg-evidence-selftest"))
    st_line = [l for l in out_st.splitlines() if l.startswith("arms=")]
    st = st_line[0] if st_line else "self-test did not report"

    out = ["# Evidence table", "",
           "Generated by `ci/evidence_table.py` at %s. Do not hand-edit: regenerate, or the row goes."
           % time.strftime("%Y-%m-%d %H:%M:%S %z"),
           "",
           "- repository commit: `%s` (working tree carries %d uncommitted faces at generation time). That is "
           "the HEAD this file was generated **under**, not the commit that contains it - the containing commit "
           "is necessarily newer, and the cells the table describes belong to the HEAD named here."
           % (head_full[:12], len(dirty.splitlines())),
           "- frozen spec `spec/cases.yaml` blob sha256: `%s`" % spec_digest,
           "- deliverable version: %s (read from the `VERSION` file at generation time - the file is the only source, and `python ci/version_face.py` refuses the tree when any face quotes a different copy)." % VERSION_VALUE,
           "- equality verdict right now: **%s**" % verdict,
           "- gate self-test: **%s**" % st,
           "- faces on disk but not read (earlier revisions or other naming): %s" % (
               ", ".join("`%s` (%d records)" % (e, n) for e, n in skipped) or "none"),
           "",
           "| port | canonical face read | required cells matched (of 44) | behaviour digest | os / arch / build |",
           "|---|---|---|---|---|",
           ]
    for port, entry, digest, n, info in ports_list:
        out.append("| %s | `%s` | %s | `%s` | %s |"
                   % (port, entry, n if n else "-", digest[:16] if digest else "-", info))
    out += ["", "## What this table does not claim", "",
            "It lists what each port emitted and the digest of its behaviour. It does not assert the ports",
            "agree - that is the equality verdict above, and until it reads PASS the deliverable is unfinished.",
            "A port excluded by the health leg is listed with its reason, not silently dropped.", ""]
    io.open(os.path.join(REPO, "docs", "evidence.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote docs/evidence.md ports=%d excluded_faces=%d verdict=%s selftest=%s"
          % (len(ports_list), len(skipped), verdict, st))
    return 0


if __name__ == "__main__":
    sys.exit(main())
