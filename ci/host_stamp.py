#!/usr/bin/env python3
"""Generate docs/host-stamp.md: the machine facts, quarantined into their own face.

Run:  python ci/host_stamp.py [--selftest]

Why this file exists. `ci/clone_parity.py` proves a stranger's clone produces the same answers as the author's
tree by comparing every generated face against its own committed blob. One of those faces -
`docs/delivery-form.md` - also carried the interpreter version of whatever machine regenerated it, so the leg's
green side was reachable only on the host whose stamp was committed. Four outside reviewers hit that on
2026-10-11/12 and reported `differing=1` on a line that describes a machine, not a measurement. The fix chosen
here is the one that removes the tolerance instead of widening it: host-dependent values live in this face,
which the parity leg names as host-bound and does not compare, and every other face is byte-identical on any
interpreter. Recorded in `docs/tickets/SG-F10-parity-leg-host-bound.md`.

Exit codes: 0 = the face was written · 3 = instrument failure (the face could not be written or read back).
This leg judges nothing, so it has no rc=1 path, and an absent denominator is a VOID run.
"""
import io
import os
import platform
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, "docs", "host-stamp.md")
FACE = "docs/host-stamp.md"


def stamp_lines():
    """The host-bound content, as a list. Kept separate from writing so the arms can test it directly."""
    return [
        "# Host stamp - generated, not comparable",
        "",
        "Generated by `ci/host_stamp.py` at %s. **This face is deliberately excluded from the reproducibility "
        "comparison** (`ci/clone_parity.py` names it as host-bound): everything in it describes the machine that "
        "ran the generator, and a stranger's machine is allowed to differ without that being a finding." % (
            time.strftime("%Y-%m-%d %H:%M:%S %z"),),
        "",
        "| host fact | value on the machine that generated this tree |",
        "|---|---|",
        "| interpreter | `%s` |" % sys.version.split()[0],
        "| implementation | `%s` |" % platform.python_implementation(),
        "| platform | `%s` |" % platform.platform(),
        "| console code page | `%s` |" % (getattr(sys.stdout, "encoding", "-") or "-"),
        "| os | `%s %s` |" % (platform.system(), platform.release()),
        "",
        "## What these values are evidence of, and what they are not",
        "",
        "- They are **not** requirements. Nothing here obliges a reader to install Python `%s`; the checker "
        "requires a Python 3 interpreter on `PATH` and nothing else, and that claim is in "
        "`docs/delivery-form.md` with its own command." % sys.version.split()[0],
        "- They **are** the reason verdicts move. This project measured a legality verdict flip between two "
        "run-times of the same language (`docs/FINDINGS-rev6.md` M7), which is why the runtime is recorded at "
        "all - and why it is recorded in a face a reader can ignore when they are checking reproducibility.",
        "- Long-path behaviour, reserved-name behaviour and console encoding are host- and manifest-dependent. "
        "`docs/claim-boundary.md` scopes every claim reached here to one Windows host; this face is the record "
        "of what that scope actually was.",
        "",
        "Reproduce it: `python ci/host_stamp.py && cat docs/host-stamp.md`. Any two runs on one machine differ "
        "only in the timestamp line, which is normalised by the parity leg for every face.",
        "",
    ]


def write_face():
    text = "\n".join(stamp_lines()) + "\n"
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    back = io.open(OUT, encoding="utf-8", newline="\n").read()
    if back != text:
        return None, 0
    return len(text.encode("utf-8")), back.count("\n")


def selftest():
    errs, arms = [], [0]

    def chk(cond, label):
        arms[0] += 1
        if not cond:
            errs.append("arm failed: %s" % label)

    lines = stamp_lines()
    chk(any(l.startswith("# Host stamp") for l in lines), "green: the face names itself")
    chk(any("deliberately excluded" in l for l in lines),
        "green: the face says on its first screen that it is not compared - a reader must not have to know the "
        "leg's internals to learn which numbers are machine-bound")
    rows = [l for l in lines if re.match(r"^\| [a-z].*\| `", l)]
    chk(len(rows) == 5, "red: exactly five host facts are recorded (%d found); a sixth appearing silently would "
                        "widen what is host-bound without anyone naming it" % len(rows))
    chk(not any("must install" in l.lower() for l in lines),
        "red: the face never presents a machine fact as a requirement on the reader")
    chk(FACE == "docs/host-stamp.md", "green: the name the parity leg excludes is the name written here")
    return errs, arms[0]


def main(argv):
    if "--selftest" in argv:
        errs, arms = selftest()
        for e in errs:
            print("SELFTEST-FAIL: %s" % e)
        print("arms=%d passed=%d" % (arms, arms - len(errs)))
        return 1 if errs else 0
    extra = [a for a in argv if a not in ("--quiet",)]
    if extra:
        print("OUTCOME=INSTRUMENT-RED this leg takes no arguments but --selftest/--quiet, got %r" % (extra,))
        return 3
    size, lines = write_face()
    if size is None:
        print("OUTCOME=INSTRUMENT-RED wrote %s and read it back differently; a face that does not survive its "
              "own write is not evidence" % FACE)
        return 3
    print("OUTCOME=CLEAN face=%s bytes=%d lines=%d host_interpreter=%s"
          % (FACE, size, lines, sys.version.split()[0]))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Exception as exc:
        print("OUTCOME=INSTRUMENT-RED %s: %s" % (type(exc).__name__, str(exc)[:160]))
        sys.exit(3)
