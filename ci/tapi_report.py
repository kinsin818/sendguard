"""Generate docs/tapi.md - the per-entry instrument self-check, per spec/gate.md section 2.

Run:  python ci/tapi_report.py

T-API is the leg that asks: did this port's harness actually drive every entry the contract pins for it,
and when several entries reach the same question, do they give the same answer? Three outcomes are
distinguished, because the first version of the clause conflated them and made agreement illegal:

  ENTRY-VARIANCE-PUBLISHED   every pinned entry ran and they agree          -> a finding
  ENTRY-DIVERGENCE-PUBLISHED every pinned entry ran and some differ           -> a finding, per entry
  ENTRY-GAP                  the harness did not run every pinned entry        -> an instrument gap, named
"""
import io
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import equality  # noqa: E402


def main():
    man = json.load(io.open(equality.REQUIRED, encoding="utf-8"))
    pinned = {}
    for row in man.get("tapi_cells_per_language", []):
        pinned.setdefault(row["language"], set()).add(row["api_entry"])
    ports, files_seen, problems, xcheck, skipped = equality.discover()
    ports.pop("_extra_counts", {})

    lines = ["# T-API - did each harness really drive every entry it was given?", "",
             "Generated by `ci/tapi_report.py` at %s from the canonical faces and "
             "`spec/cells-required.json`." % time.strftime("%Y-%m-%d %H:%M:%S %z"),
             "",
             "`spec/gate.md` section 2 (as corrected by rev4 and re-stated in rev8): running every pinned "
             "entry and",
             "getting the same answer is **a finding**, not a failure; not running them is an instrument gap "
             "and is",
             "named. T-API cells never gate the equality verdict - they gate trust in the harness.",
             "",
             "| port | pinned entries | entries seen in its face | tapi rows landed | verdict |",
             "|---|---|---|---|---|"]
    gaps = []
    for port in sorted(set(pinned) | set(ports)):
        want = pinned.get(port, set())
        rows = [c for k, lst in (ports.get(port) or {}).items() if k[0] == "tapi" for c in lst]
        seen_entries = {str(c.get("api_entry")) for k, lst in (ports.get(port) or {}).items() for c in lst}
        covered = sorted(want & seen_entries)
        missing = sorted(want - seen_entries)
        if port not in ports:
            word = 'FACE-EXCLUDED (no canonical face is read; see docs/evidence.md)'
        elif not rows and missing:
            word = "ENTRY-GAP (no T-API rows; %d pinned entry/entries never seen)" % len(missing)
            gaps.append((port, missing, word))
        elif missing:
            word = "ENTRY-GAP (%d pinned entries never seen: %s)" % (len(missing), ", ".join(missing))
            gaps.append((port, missing, word))
        elif not want:
            word = "no entries pinned for this language"
        else:
            word = "%d/%d pinned entries present; %d T-API row(s)" % (len(covered), len(want), len(rows))
        lines.append("| %s | %d | %d | %d | %s |"
                     % (port, len(want), len(covered), len(rows), word))

    lines += ["", "## Does an entry change the answer? (published, not judged)", ""]
    any_spread = 0
    for port in sorted(ports):
        by_cell = {}
        for k, lst in ports[port].items():
            if k[0] == "tapi":
                continue
            by_cell.setdefault(equality.fmt(k), []).append(lst[0])
        multi = {c: rows for c, rows in by_cell.items() if len(rows) > 1}
        spread = 0
        for c, rows in sorted(multi.items()):
            vals = {tuple(sorted((f, str(equality.canon_value(f, r))) for f in equality.VERDICT_FIELDS))
                    for r in rows}
            if len(vals) > 1:
                spread += 1
        if multi:
            any_spread += 1
            lines.append("- `%s`: %d cells answered by more than one entry, %d of them give different "
                         "verdicts across entries -> %s"
                         % (port, len(multi), spread,
                            "entry-divergence-published" if spread else "entry-variance-published (agree)"))
        else:
            lines.append("- `%s`: every non-T-API cell was answered once, so this port's entry spread is "
                         "not observable from its published rows%s"
                         % (port, " - see the gap column above" if port in dict(
                             (g[0], 1) for g in gaps) else ""))
    lines += ["", "## What this leg is for", "",
              "A harness that quietly used one call for every cell would look identical to a harness that "
              "drove the language's whole pinned entry list - and the difference decides whether the "
              "'independent implementations' sentence is true. That is why the counts above are printed "
              "even when they are unflattering: the contract pins the entries, so an entry the harness "
              "never touched is a gap in the instrument, not a missing measurement about Windows.", ""]
    text = "\n".join(lines) + "\n"
    io.open(os.path.join(REPO, "docs", "tapi.md"), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote docs/tapi.md bytes=%d entry_gaps=%d" % (len(text.encode("utf-8")), len(gaps)))
    for port, missing, word in gaps:
        print("   ENTRY-GAP %s: %s" % (port, ", ".join(missing)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
