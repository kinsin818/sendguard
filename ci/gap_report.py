"""Per-port gap against the required list, generated rather than hand-typed.

Run:  python ci/gap_report.py [--out docs/GAP.md]

The numbers come from ci/equality.py's own identity rules, so this file and the gate can never disagree
about what "the same cell" means -- which is the defect that made six ports spell six names for one
question. A port is finished when its missing list is empty, or every missing cell carries status
`blocked` with the command, its exit code and one attempted fix.
"""
import argparse
import glob
import io
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import equality  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "docs", "GAP.md"))
    a = ap.parse_args()

    man = json.load(io.open(equality.REQUIRED, encoding="utf-8"))
    req = {}
    for r in man["required_cells"]:
        req[(r["case_group"], r["case_id"], tuple(sorted((r.get("sub_identity") or {}).items())))] = r

    ports, files_seen, problems, xcheck, skipped = equality.discover()
    extras = ports.pop("_extra_counts", {})
    cells = {}
    for port in sorted(ports):
        got = {}
        for key, lst in ports[port].items():
            if key[0] == "tapi":
                continue
            got[key] = lst[0]
        cells[port] = got

    lines = ["# Per-port gap against the required list", "",
             "Generated by `ci/gap_report.py` at %s from `%s` (%d required cells)."
             % (time.strftime("%Y-%m-%d %H:%M:%S %z"),
                 os.path.relpath(equality.REQUIRED, REPO).replace("\\", "/"), len(req)),
             "",
             "Identity rules are ci/equality.py's: spelling drift is folded (B1 / BLIND-1 / T-BLIND-1, "
             "T09a / T09-m1), a bare family id is not folded into a member, and only the canonical face "
             "`results/<port>.<os>.<arch>/` is read.", ""]
    if skipped:
        lines.append("Non-canonical faces excluded: %s"
                     % ", ".join("`results/%s` (%d records)" % (e, n) for e, n in skipped))
        lines.append("")
    if problems:
        lines.append("Load problems: %d (%s)" % (len(problems), problems[0][:80]))
        lines.append("")

    declared = sorted(man["primary_entry_per_port"])
    missing_faces = [d for d in declared if d not in cells or not cells[d]]
    if missing_faces:
        lines.append("### Ports the contract declares with no readable cells at generation time")
        lines.append("")
        for d in missing_faces:
            lines.append("- FACE-MISSING `%s` - the required list names a primary entry for it, so this is"
                         % d)
            lines.append("  not a row that can be quietly dropped from the denominator.")
        lines.append("")

    total_missing = 0
    for port in sorted(cells):
        have = set(cells[port])
        missing = sorted(k for k in req if k not in have)
        stray = sorted(k for k in have if k not in req)
        total_missing += len(missing)
        lines.append("## %s - matched %d/%d, missing %d, outside-list %d, extra-flagged %d"
                     % (port, len(have & set(req)), len(req), len(missing), len(stray),
                        extras.get(port, 0)))
        for k in missing:
            lines.append("  - MISSING `%s`" % equality.fmt(k))
        for k in stray[:10]:
            lines.append("  - outside list (keep it, mark `extra: true`): `%s`" % equality.fmt(k))
        if len(stray) > 10:
            lines.append("  - ...and %d more outside-list cells" % (len(stray) - 10))
        lines.append("")
    lines.append("**total missing cells across ports with a face = %d**; declared ports without a face = %d%s"
                 % (total_missing, len(missing_faces),
                    " (%s)" % ", ".join(missing_faces) if missing_faces else ""))
    text = "\n".join(lines) + "\n"
    io.open(a.out, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s bytes=%d ports=%d total_missing=%d"
          % (os.path.relpath(a.out, REPO).replace("\\", "/"), len(text.encode("utf-8")),
             len(cells), total_missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
