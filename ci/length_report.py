"""Generate docs/length-family.md: what each port recorded about the length traps, without pretending
the rungs are comparable while their fillers differ.

    python ci/length_report.py

The required length cells line up on rung and path form but not on the bytes of the component (rev7
measured six different fillers), so no cross-port verdict is claimed here. What CAN be published honestly is
each port's own record, side by side, including the three different things the field `len_triple` is being
used for, and the one row that looks like an API property rather than an artefact.
"""
import io
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import equality  # noqa: E402

RUNGS = [(78, "plain"), (78, "extended"), (120, "plain"), (120, "extended"),
         (200, "plain"), (200, "extended")]
TRAPS = ["T17", "T18"]


def shape(cell):
    """What did this port actually put in name_source: the bytes it passed, a label, or nothing?"""
    ns = cell.get("name_source")
    if not isinstance(ns, str) or not ns:
        return "absent"
    if re.fullmatch(r"(?:[0-9a-fA-F]{2})+", ns):
        try:
            dec = bytes.fromhex(ns).decode("utf-8")
        except Exception:
            return "hex-undecodable"
        if looks_like_label(dec):
            return "label(%s)" % dec[:26]
        return "bytes(%d units)" % len(dec)
    return "label(%s)" % ns[:26] if looks_like_label(ns) else "text(%s)" % ns[:22]


def looks_like_label(s):
    """A field that should hold the bytes passed, holding a description instead. Measured on the frozen
    spec's own prose sample: 'T-LEN-PATH (length bisection, G1-G4)'."""
    return ("LEN" in s) or (" " in s and "." not in s.split(" ")[0]) or bool(re.search(r"bisect", s))


def triple_shape(cell):
    t = cell.get("len_triple")
    if t is None:
        return "not recorded"
    if isinstance(t, dict):
        if "requested" in t or "landed" in t:
            sub = t.get("requested") or {}
            return "requested=%s" % "/".join(str(sub.get(k, "-")) for k in
                                             ("code_points", "utf16_code_units", "utf8_bytes"))
        return "/".join(str(t.get(k, "-")) for k in ("code_points", "utf16_code_units", "utf8_bytes"))
    if isinstance(t, (list, tuple)):
        return "/".join(str(x) for x in t)
    return str(t)


def filler_holdouts():
    """Which ports do not share the majority component bytes on the pinned rungs.

    A cell is excluded when *any* port's input differs, so the useful sentence is not 'twelve cells are
    unpinned' but 'which port is holding them'. Computed, not remembered.
    """
    bad = set()
    for trap in TRAPS:
        for base, form in RUNGS:
            per = {}
            for p in sorted(cells_global):
                for k, c in cells_global[p].items():
                    if k[0] == "len" and k[1] == trap and c.get("base_len") == base                             and c.get("path_form") == form:
                        per[p] = equality.canon_name(c.get("name_source"))[1]
            if not per:
                continue
            counts = {}
            for p, v in per.items():
                counts[v] = counts.get(v, 0) + 1
            keep = max(counts, key=lambda v: counts[v])
            bad |= {p for p, v in per.items() if v != keep and counts[v] == 1}
    return ", ".join(sorted(bad)) or "none"


def main():
    ports, files_seen, problems, xcheck, skipped = equality.discover()
    ports.pop("_extra_counts", {})
    declared = sorted(json.load(io.open(equality.REQUIRED, encoding="utf-8"))["primary_entry_per_port"])
    cells = {p: {k: lst[0] for k, lst in ports[p].items()} for p in ports}
    global cells_global
    cells_global = cells
    lines = ["# The length family, disclosed rather than compared", "",
             "Generated by `ci/length_report.py` at %s. Six fillers were measured for the same rung"
             % time.strftime("%Y-%m-%d %H:%M:%S %z"),
             "(rev6), so the required length cells are excluded from the equality gate as `unpinned_input`",
             "and **this document claims no cross-port verdict**. What it publishes is each port's own",
             "record, because the pattern in it is the reason to fix the filler rather than drop the family.",
             ""]
    for trap in TRAPS:
        for base, form in RUNGS:
            pass
    lines.append("| trap | rung | path form | port | create_result | name_source is | len_triple records |")
    lines.append("|---|---|---|---|---|---|---|")
    oddities = []
    for trap in TRAPS:
        for base, form in RUNGS:
            key = (trap, (base, form))
            for p in declared:
                hit = None
                if p in cells:
                    for k, c in cells[p].items():
                        if k[0] == "len" and k[1] == trap and c.get("base_len") == base \
                                and c.get("path_form") == form:
                            hit = c
                            break
                if hit is None:
                    lines.append("| %s | %d | %s | %s | (no cell) | - | - |" % (trap, base, form, p))
                    continue
                lines.append("| %s | %d | %s | %s | %s | %s | %s |"
                             % (trap, base, form, p, str(hit.get("create_result")),
                                shape(hit), triple_shape(hit)))
    lines += ["", "## What the table shows, stated at the strength the data supports", ""]
    by_port = {}
    for trap in TRAPS:
        for base, form in RUNGS:
            for p in declared:
                if p not in cells:
                    continue
                for k, c in cells[p].items():
                    if k[0] == "len" and k[1] == trap and c.get("path_form") == form:
                        by_port.setdefault((p, form), set()).add(str(c.get("create_result")))
    for (p, form), vals in sorted(by_port.items()):
        if len(vals) > 1 or "err_at_parse" in vals:
            oddities.append("`%s` on the **%s** form: %s" % (p, form, ", ".join(sorted(vals))))
    lines += ["- Ports that refuse the extended (`\\\\?\\`) form at *parse* rather than at the filesystem:",
              "  %s" % ("; ".join(sorted(set(oddities))) or "none recorded"),
              "  That is the shape of an API property, not of a measurement error, and it is the one row in",
              "  this family worth asking about directly - it is also exactly the kind of answer a single-",
              "  language checker would hand a client as if it were about Windows.",
              "- Ports that put a **case label** in `name_source` instead of the bytes they passed, and",
              "  therefore have no recorded name at all for these cells: %s"
              % (", ".join(sorted({p for p in declared for k, c in (cells.get(p) or {}).items()
                                 if k[0] == "len" and shape(c).startswith("label")})) or "none"),
              "- Ports whose `len_triple` is not the width of the requested name: %s"
              % (", ".join(sorted({p for p in declared for k, c in (cells.get(p) or {}).items()
                                  if k[0] == "len" and triple_shape(c).startswith("requested=")}))
                 or "none"),
              "- Ports still recording a component the others did not receive: %s"
              % filler_holdouts(),
              "  The equality gate excludes a cell from comparison when any port's input bytes differ, so",
              "  one port's filler holds up all twelve rungs - named here because that is the shortest path",
              "  from this document to a comparable length family.",
              "",
              "Once the filler is pinned (rev7), the rung cells can be compared and this file becomes a",
              "verdict table instead of a disclosure. Until then a reader who wants a length answer from it",
              "is being given the wrong kind of number, and this document says so at the top.",
              ""]
    text = "\n".join(lines) + "\n"
    io.open(os.path.join(REPO, "docs", "length-family.md"), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote docs/length-family.md bytes=%d rows=%d"
          % (len(text.encode("utf-8")), sum(1 for l in lines if l.startswith("| T"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
