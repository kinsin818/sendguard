"""Generate docs/matrix.md: the (cell x port) grid of checker verdicts, from the committed faces.

Run:  python ci/matrix_table.py

Why this is generated and not typed: the grid is the artifact a reader actually wants - one row per
question, one column per port, and the cells that differ are visible without reading six JSON files. If a
human typed it, the only guarantee would be that it matches whatever was true when it was typed. The row
labels, the folding of spelling drift and the canonicalisation of representations all come from
ci/equality.py, so this table and the gate cannot disagree about what one cell means.

Words printed per cell:
  value           the canonical verdict, abbreviated
  -               this port recorded no value for that field on that cell
  ?               the cell is not comparable (different input bytes, or a different layer asked)
"""
import io
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import equality  # noqa: E402

SHOW = [("os_legality_verdict", "legal?"), ("create_result", "create"),
        ("bytes_on_disk", "disk"), ("name_landed_as", "landed"),
        ("name_mutated", "mut"), ("mechanism_class", "mechanism")]
SHORT = {"err_at_syscall": "err@fs", "err_at_parse": "err@parse", "not_applicable": "n/a",
         "illegal_char_filter": "illegal-char", "reserved_device_name": "device-name",
         "path_preprocessing_policy": "strip-set", "normalization_form": "norm"}


def fmt_value(field, v):
    if v is None or v == equality.ABSENT or v[0] in ("x", "null"):
        return "-"
    s = str(v[1])
    if field == "name_landed_as" and v[0] == "h":
        try:
            s = bytes.fromhex(s).decode("utf-8")
        except Exception:
            s = "hex:" + s[:10]
    if len(s) > 40:
        s = s[:38] + ".."
    return SHORT.get(s, s)


def main():
    man = json.load(io.open(equality.REQUIRED, encoding="utf-8"))
    req = [(r["case_group"], r["case_id"], tuple(sorted((r.get("sub_identity") or {}).items())))
           for r in man["required_cells"] if r["case_group"] != "tapi"]
    ports, files_seen, problems, xcheck, skipped = equality.discover()
    ports.pop("_extra_counts", {})
    cells = {p: {k: lst[0] for k, lst in ports[p].items() if k[0] != "tapi"} for p in ports}
    names = sorted(cells)

    # comparability per cell, using the gate's own rules
    unpinned, incomparable = set(), set()
    for k in {kk for p in names for kk in cells[p]}:
        holders = [p for p in names if k in cells[p]]
        if len(holders) < 2:
            continue
        forms = {equality.canon_name(cells[p][k].get("name_source") or cells[p][k].get("requested_name")
                                     or cells[p][k].get("name_landed_as")) for p in holders}
        forms.discard(("x", None))
        if len(forms) > 1:
            unpinned.add(k)
            continue
        for f in equality.CELL_LEVEL_FIELDS:
            vals = {str(equality.canon_value(f, cells[p][k])) for p in holders}
            vals.discard(str(equality.ABSENT))
            if len(vals) > 1:
                incomparable.add(k)
                break

    lines = ["# Matrix A - one question, six answers (Windows x64, this host)", "",
             "Generated by `ci/matrix_table.py` at %s from the canonical faces %s."
             % (time.strftime("%Y-%m-%d %H:%M:%S %z"), ", ".join("`%s.windows.x64`" % n for n in names)),
             "",
             "Fields shown per cell, in this order: %s." % ", ".join(f for f, _ in SHOW),
             "",
             "A row where every column matches is a row where six independent implementations of one spec",
             "reached the same verdict. A row where they differ is the finding, and the last column names the",
             "field that differs so a reader does not have to eyeball six strings.",
             "",
             "- `-` inside a value: that port recorded no value for that field (never read as agreement).",
             "- `(not run)`: that port has no record for that cell at all; see `docs/GAP.md`.",
             "- `?`: this port asked a different layer or path form than the others on this cell, so its",
             "  answer is about a different question. The other columns still show their data.",
             "- A landed name that is a prefix of the pinned input is flagged by the gate as",
             "  `PREFIX-SHAPED`, because the two explanations cannot be told apart from the bytes alone:",
             "  Windows really does drop a trailing dot, and a port really can cut its own hex at a display",
             "  width. The flag names the rows to check; it does not remove a value from the comparison.", ""]
    header = "| cell | " + " | ".join(names) + " | agree | which field differs |"
    lines += [header, "|---" * (len(names) + 4) + "|"]

    # The agree/differ column comes from the gate's own verdict artifact, not from a second implementation
    # of the comparison rules. Measured reason: this table judged by plain string equality and disagreed
    # with ci/equality.py about the same data (15 agree / 29 differ against the gate's 24 / 54) - the
    # two-rulers defect this project has now caught in itself more than once.
    vpath = os.path.join(REPO, "evidence", "judgement", "equality-verdict.json")
    if not os.path.isfile(vpath):
        print("REFUSING: the gate's verdict artifact is missing. Run `python ci/equality.py` first; "
              "re-judging with a second ruler is exactly what this file must not do")
        return 3
    verdict = json.load(io.open(vpath, encoding="utf-8"))
    if verdict.get("source_results") != "results":
        print("REFUSING: the verdict was written from %r, not from this repository's results/ face - "
              "a fixture verdict must not drive the published matrix" % verdict.get("source_results"))
        return 3
    disagree_cells = {}
    for key, field, ports in verdict["disagreements"]:
        disagree_cells.setdefault(key, []).append(field)
    abstain_cells = {c[0] for c in verdict["channel_abstentions"]}
    crossform_cells = {c[0] for c in verdict["name_cross_form_agreements"]}
    excluded_cells = set(verdict["unpinned_input"]) | set(verdict["cells_excluded"])
    prefix_cells = {c[0] for c in verdict["prefix_shaped_records"]}

    agree_rows = differ_rows = 0
    for k in sorted(req):
        holders = [p for p in names if k in cells[p]]
        if not holders:
            continue
        # a port that asked a different layer is blanked, not the whole row: five comparable
        # answers must stay visible, or one port's missing channel erases the other five's data.
        odd = set()
        if k in unpinned or k in incomparable:
            for f in equality.CELL_LEVEL_FIELDS:
                per = {p: str(equality.canon_value(f, cells[p][k])) for p in holders}
                modes = {}
                for p, v in per.items():
                    modes.setdefault(v, []).append(p)
                if len(modes) > 1:
                    common = max(modes.values(), key=len)
                    odd |= {p for p in per if p not in common}
        vals = {}
        for p in names:
            if k not in cells[p]:
                vals[p] = "(not run)"
                continue
            if p in odd:
                vals[p] = "?"
                continue
            bits = [fmt_value(f, equality.canon_value(f, cells[p][k])) for f, _ in SHOW]
            vals[p] = "/".join(bits)
        key = equality.fmt(k)
        marks = disagree_cells.get(key, [])
        if key in excluded_cells:
            word = "not comparable"
        elif marks:
            differ_rows += 1
            word = "NO"
        else:
            agree_rows += 1
            word = "yes"
        extra = []
        if key in abstain_cells:
            extra.append("legality field abstained")
        if key in crossform_cells:
            extra.append("names matched across encodings")
        if key in prefix_cells:
            extra.append("prefix-shaped name record")
        lines.append("| %s | %s | %s | %s |" % (
            key,
            " | ".join(vals[p].replace("|", "\\|")[:24] for p in names),
            word,
            ", ".join(marks + extra) or "-"))
    lines += ["", "**rows: agree=%d differ=%d** (of %d required cells that at least one port answered)"
              % (agree_rows, differ_rows, agree_rows + differ_rows), ""]
    if unpinned:
        lines.append("Cells not compared because the ports used different input bytes: %s"
                     % ", ".join("`%s`" % equality.fmt(k) for k in sorted(unpinned)))
    if incomparable:
        lines.append("Cells not compared because the ports asked a different layer or path form: %s"
                     % ", ".join("`%s`" % equality.fmt(k) for k in sorted(incomparable)))
    lines += ["", "Missing required cells per port are in `docs/GAP.md`; this table does not restate them.",
              ""]
    text = "\n".join(lines) + "\n"
    io.open(os.path.join(REPO, "docs", "matrix.md"), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote docs/matrix.md bytes=%d rows_agree=%d rows_differ=%d unpinned=%d incomparable=%d"
          % (len(text.encode("utf-8")), agree_rows, differ_rows, len(unpinned), len(incomparable)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
