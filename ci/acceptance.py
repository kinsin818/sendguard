"""Generate docs/acceptance-S02.md - the acceptance sheet for the six port windows.

Run:  python ci/acceptance.py

One row per port, and every number is read back from disk or from the gate's artifact: the reply a window
sent is quoted as what the window *claimed*, and set beside what the tree actually holds. The two are
allowed to disagree - that disagreement is the point of an acceptance sheet, and it is how this project
caught itself twice (a face that went empty, and a port that had not run all its pinned entries).
"""
import glob
import io
import json
import os
import re
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import equality  # noqa: E402
import validate_cells  # noqa: E402

GROUPS = ("trap", "ctrl", "blind", "len")


def main():
    man = json.load(io.open(equality.REQUIRED, encoding="utf-8"))
    req = {(r["case_group"], r["case_id"], tuple(sorted((r.get("sub_identity") or {}).items())))
           for r in man["required_cells"]}
    pinned = {}
    for row in man.get("tapi_cells_per_language", []):
        pinned.setdefault(row["language"], set()).add(row["api_entry"])
    vpath = os.path.join(REPO, "evidence", "S02", "equality-verdict.json")
    verdict = json.load(io.open(vpath, encoding="utf-8")) if os.path.isfile(vpath) else None
    ports, files_seen, problems, xcheck, skipped = equality.discover()
    extras = ports.pop("_extra_counts", {})

    lines = ["# Acceptance sheet - S02 (six ports, one contract)", "",
             "Generated by `ci/acceptance.py` at %s. 'reported' columns are what the window's own "
             "self-check file states; 'on disk' columns are read from the canonical face. They are printed "
             "side by side on purpose." % time.strftime("%Y-%m-%d %H:%M:%S %z"), "",
             "| port | cells on disk | required matched | missing | blocked | extra | pinned entries seen | "
             "controls | schema-invalid (outside ruler) | self-reported valid | verdict | self-check file |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for port in sorted(set(ports) | {"typescript"}):
        face = os.path.join(REPO, "results", "%s.windows.x64" % port)
        files = glob.glob(os.path.join(face, "**", "*.json"), recursive=True) if os.path.isdir(face) else []
        cells = {k: lst[0] for k, lst in (ports.get(port) or {}).items() if k[0] in GROUPS or k[0] in req}
        matched = len(set(cells) & req)
        missing = len(req - set(cells))
        blocked = sum(1 for c in cells.values()
                      if str(c.get("run_status")) == "blocked" or c.get("blocked") is True)
        entries = {str(c.get("api_entry")) for k, lst in (ports.get(port) or {}).items() for c in lst}
        want = pinned.get(port, set())
        seen = sorted(want & entries)
        controls = "n/a"
        for c in [x for lst in (ports.get(port) or []).values() for x in lst]:
            if c.get("case_group") == "ctrl" and c.get("control_pass") is False:
                controls = "FAILED"
                break
        else:
            ctrl_rows = [c for k, lst in (ports.get(port) or {}).items() for c in lst
                         if k[0] == "ctrl"]
            controls = ("pass (%d/%d stamped)" % (sum(1 for c in ctrl_rows if c.get("control_pass") is True),
                                                   len(ctrl_rows))) if ctrl_rows else "not stamped"
        rep = "-"
        sc = os.path.join(REPO, "evidence", "S02", "%s-selfcheck.md" % port)
        if os.path.isfile(sc):
            text = io.open(sc, encoding="utf-8", errors="replace").read()
            m = re.search(r"cells_required=\d+[^\n]*", text)
            rep = (m.group(0)[:70] if m else "file present, no cells_required line")
            screl = "evidence/S02/%s-selfcheck.md" % port
        else:
            screl = "(missing)"
        schema = json.load(io.open(validate_cells.SCHEMA, encoding="utf-8"))
        bad = 0
        for f, cell, err in validate_cells.cells_in(face):
            if err or validate_cells.check(cell, schema):
                bad += 1
        selfrep = "-"
        sc0 = os.path.join(REPO, "evidence", "S02", "%s-selfcheck.md" % port)
        if os.path.isfile(sc0):
            m0 = re.search(r"cells_valid[= ]+(\d+)", io.open(sc0, encoding="utf-8",
                                                               errors="replace").read())
            if m0:
                selfrep = m0.group(1)
        word = "OK"
        if bad and word == "OK":
            word = "OK (schema-invalid %d)" % bad
        if not files:
            word = "FACE-MISSING"
        elif missing:
            word = "INCOMPLETE (%d cells)" % missing
        elif want and len(seen) < len(want):
            word = "ENTRY-GAP (%d/%d)" % (len(seen), len(want))
        lines.append("| %s | %d | %d/%d | %d | %d | %d | %d/%d | %s | %d | %s | %s | `%s` (%s) |"
                     % (port, len(files), matched, len(req), missing, blocked,
                        extras.get(port, 0), len(seen), len(want), controls, bad, selfrep, word, rep, screl))

    lines += ["", "## Gate reading for the same tree", ""]
    if verdict:
        lines += ["- outcome: **%s**, cells compared %d, cells with no verdict conflict %d, "
                  "conflicting verdict facts %d, channel abstentions %d, required cells missing %d"
                  % (verdict["outcome"], verdict["cells_compared"],
                     verdict["cells_with_no_verdict_disagreement"], len(verdict["disagreements"]),
                     len(verdict["channel_abstentions"]), 0 if not verdict["unpinned_input"] else "?"),
                  "- source face recorded inside the artifact: `%s` (this sheet refuses to quote a verdict "
                  "computed anywhere else)" % verdict.get("source_results"), ""]
    else:
        lines += ["- no verdict artifact: run `python ci/equality.py` first; this sheet does not "
                  "re-implement the comparison.", ""]

    if skipped:
        lines += ["## Faces on disk that the contract does not read", ""]
        for e, n in skipped:
            lines.append("- `results/%s` - %d records. On disk, published in history, **not compared**: "
                         "either an earlier contract revision of the same port or a port that "
                         "self-declared INSTRUMENT-RED." % (e, n))
        lines.append("")

    lines += ["## What acceptance here does not mean", "",
              "- `schema-invalid` counts cells that do not carry the fields `spec/schema.json` requires. It "
              "is computed by `ci/validate_cells.py`, the same ruler `docs/cell-validation.md` is written "
              "from, and it is printed beside each port's own self-reported count because a window grading "
              "its own homework is the failure this leg exists to catch.",
              "",
              "A row is 'OK' when the required cells exist on the canonical face, not when the port's "
              "answers are correct - correctness against the spec is the sealed expectation table's job "
              "(`docs/expected-summary.md`), and agreement between ports is the gate's job "
              "(`docs/STATUS.md`). A port that ran one entry out of its pinned list shows ENTRY-GAP even "
              "with a full cell count, because an unexercised entry is a claim about the harness that the "
              "harness did not test.", ""]
    text = "\n".join(lines) + "\n"
    io.open(os.path.join(REPO, "docs", "acceptance-S02.md"), "w", encoding="utf-8", newline="\n").write(text)
    print("wrote docs/acceptance-S02.md bytes=%d ports=%d faces_excluded=%d"
          % (len(text.encode("utf-8")), len(ports), len(skipped)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
